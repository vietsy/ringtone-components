import type { LoadOutcome } from "@rightone/ui";
import { recordTranslation, translationRegister } from "@/lib/mock/backend/translations";
import { mockTranslationsFailure, type TranslationsView } from "@/lib/mock/translations";
import type { VersionPhase, VersionStatus } from "./public";
import type { Staff } from "./session";
import { NOT_CONFIGURED, usesMockData } from "./source";

/**
 * SVC's seam for the translation register (SCR-SVC-21): `GET /translations` reads the translations of one piece of
 * published content with the Vietnamese version each was approved against and the version in force;
 * `POST /translations` records an approved translation against an approved Vietnamese version. The Vietnamese text is
 * the authoritative one, and a translation is current only while its source version is.
 */

/** `service_ops.published_translations.translation_state`: generated by the supersession sweep, never typed. */
export type TranslationState = "current" | "superseded";

/** One approved translation, with the Vietnamese version it was approved against and where that version stands now. */
export interface TranslationRow {
  id: string;
  languageCode: string;
  sourceVersion: string;
  /** The source version's place now: in force, upcoming, or superseded by a later one. */
  sourcePhase: VersionPhase | null;
  state: TranslationState;
  approvedBy: string;
  approvedAt: string;
  /** When a later Vietnamese version took effect, and which; null while current. */
  supersededAt: string | null;
  supersededByVersion: string | null;
}

/** A version of the Vietnamese source the record form offers, with its status in the publishing module. */
export interface SourceVersionOption {
  label: string;
  status: VersionStatus;
  phase: VersionPhase | null;
  effectiveFrom: string | null;
}

/** `GET /translations` for one content key: current translations first, and the Vietnamese version in force. */
export interface TranslationRegister {
  contentKey: string;
  /** The Vietnamese text a reader is offered where no current translation exists; null before any takes effect. */
  inForce: { label: string; effectiveFrom: string | null } | null;
  versions: readonly SourceVersionOption[];
  translations: readonly TranslationRow[];
  /** The languages a translation of this content may be recorded in: those its publisher carries beside Vietnamese. */
  languages: readonly string[];
  readAt: string;
}

export type TranslationRefusal = "FIELD_MISSING" | "SOURCE_VERSION_NOT_APPROVED" | "TRANSLATION_ALREADY_RECORDED";

/** A command's answer: what was recorded, or the refusal with the field it concerns and the values its words name. */
export type TranslationAnswer<T> =
  | { accepted: T; refusal: null }
  | { accepted: null; refusal: { code: TranslationRefusal; field: "content_key" | "language_code" | "source_version" | null; values: Readonly<Record<string, string>> } };

/** `POST /translations` as the form sends it, every field as typed. */
export interface TranslationInput {
  contentKey: string;
  languageCode: string;
  sourceVersion: string;
}

/** What "Ghi bản dịch" left for the page: the translation recorded, or the refusal with what was typed. */
export interface TranslationAttempt {
  contentKey: string;
  input: TranslationInput;
  recorded: { languageCode: string; sourceVersion: string } | null;
  refusal: NonNullable<TranslationAnswer<never>["refusal"]> | null;
}

/** SCR-SVC-21's read: the translations of the content key typed, or CONTENT_NOT_FOUND where nothing is published under it. */
export function loadTranslations(staff: Staff, contentKey: string, view: TranslationsView | null): Promise<LoadOutcome<TranslationRegister>> {
  if (!usesMockData()) return Promise.resolve(NOT_CONFIGURED);
  if (view === "error") return Promise.resolve(mockTranslationsFailure());
  return Promise.resolve(translationRegister(staff.sessionId, { roles: staff.roles, name: staff.account }, contentKey));
}

/** "Ghi bản dịch" on SCR-SVC-21: `POST /translations`. */
export function sendTranslation(staff: Staff, input: TranslationInput): Promise<LoadOutcome<TranslationAnswer<{ id: string }>>> {
  if (!usesMockData()) return Promise.resolve(NOT_CONFIGURED);
  return Promise.resolve(recordTranslation(staff.sessionId, { roles: staff.roles, name: staff.account }, input));
}
