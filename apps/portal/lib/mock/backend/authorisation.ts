/*
 * The verification route of the party register (PTY, FR-PTY-046 and 047), as the API will behave: the public
 * register an enquirer picks a premises from, the authorities to collect for each premises, and the reads the
 * route records. POST /authority-verifications checks what the contract checks, in UC-PTY-05's order, answers
 * with one of its three answers or the codes of `design/04-refusal-codes.md`, and records every answer it gives
 * in `party.verification_reads` (DA-66: an unrecorded route cannot show overlapping collection). A refusal is
 * recorded in the module's audit log with its code (@AC-FR-PTY-047-05, -06).
 *
 * Whether the enquirer is a collecting organisation is CAT's answer, which the seam reads and hands in; this
 * family keeps no register of collecting organisations (PTY srs/07, ICatalogueReader). The premises are the premises
 * register's own (`premises.ts`): one admitted on SCR-PTY-06 can be asked about at once, and a premises whose
 * relationship had ended at the instant, or had never begun, grants nobody (DR-201 rows 7 and 8, FR-PTY-039).
 */

/** DR-201's reason code behind an answer, generated by the rule and kept with the read, never shown. */
type ReasonCode = "AUTHORITY_EFFECTIVE" | "NO_AUTHORITY" | "AUTHORITY_NOT_STARTED" | "AUTHORITY_EXPIRED" | "RELATIONSHIP_ENDED" | "NO_RELATIONSHIP";

/** One row of `party.verification_reads`: append-only. */
interface VerificationRead {
  id: string;
  enquiringOrganisation: string;
  premises: string;
  askedAtInstant: string;
  answer: VerificationAnswer;
  reasonCode: ReasonCode;
  readAt: string;
}

interface AuditEntry {
  code: VerifyRefusal | "OVERLAP_REPORT_RESERVED";
  organisation: string;
  at: string;
}

interface Verification {
  authorities: SeedAuthority[];
  reads: VerificationRead[];
  audit: AuditEntry[];
}

function state(sessionId: string): Verification {
  return table<Verification>(sessionId, "authorisation", () => ({
    authorities: AUTHORITIES.map((authority) => ({ ...authority })),
    reads: [],
    audit: [],
  }));
}

const VN_OFFSET = "+07:00";

/** The first instant of a calendar day in Vietnam time, as a time value. */
const startOf = (day: string): number => Date.parse(`${day}T00:00:00${VN_OFFSET}`);

/** Where an instant falls against an authority's period: both days are included, an open end is unbounded. */
function against(authority: SeedAuthority, at: number): "before" | "inside" | "after" {
  if (authority.from !== null && at < startOf(authority.from)) return "before";
  // The last day is included: the period ends where the next day begins.
  if (authority.to !== null && at >= startOf(authority.to) + 24 * 60 * 60 * 1000) return "after";
  return "inside";
}

/** The register the enquirer picks a premises from: every entry of the premises register whose ward it records. */
function premisesRegister(sessionId: string): RegisterPremises[] {
  return registerEntries(sessionId)
    .filter((entry): entry is typeof entry & { ward: string } => entry.ward !== null)
    .map((entry) => ({ reference: entry.record, name: entry.name, ward: entry.ward }));
}

/** One premises of the register by its record, as the enquirer reads it; null where the register holds none. */
function registerPremises(sessionId: string, record: string): RegisterPremises | null {
  const entry = registerEntries(sessionId).find((candidate) => candidate.record === record);
  return entry !== undefined ? { reference: entry.record, name: entry.name, ward: entry.ward ?? "" } : null;
}

const EMPTY: VerifyQuestion = { premises: "", date: "", time: "" };

/**
 * SCR-PTY-17 as the session reads it: the empty question, or the last enquiry's question with its result. An
 * organisation that may not use the route reads the refusal and nothing of the register, and one whose enquiry
 * was refused for that reason reads the same, whatever its standing said when the page opened.
 */
export function enquiryForm(sessionId: string, registered: boolean, attempt: VerifyAttempt | null): LoadOutcome<VerifyAuthorisation> {
  const refusedAsking = attempt?.result.kind === "refused" && attempt.result.code === "NOT_A_REGISTERED_COLLECTING_ORGANISATION";
  const may = registered && !refusedAsking;
  return {
    data: {
      registered: may,
      register: may ? premisesRegister(sessionId) : [],
      today: today(),
      question: may && attempt !== null ? attempt.question : EMPTY,
      result: may && attempt !== null ? attempt.result : { kind: "none" },
    },
    failure: null,
  };
}

/**
 * POST /authority-verifications. In UC-PTY-05's order: an enquirer that is not a registered collecting
 * organisation is refused and nothing about the premises is returned (step 2); an instant later than the
 * request is refused, naming the time of the request (step 3, FR-PTY-046); a premises the register does not hold
 * is PREMISES_NOT_FOUND. Otherwise the enquirer's own authority answers first (step 4), then whether somebody
 * else's was in effect (steps 5 and 6), and the read is recorded (step 7). A standing that cannot be read
 * (`registered` null) fails closed with no answer and nothing shared.
 */
export function verifyAuthorityScope(
  sessionId: string,
  enquirer: { organisation: string; registered: boolean | null },
  input: { premises: string; at: string },
): VerifyResult {
  if (enquirer.registered === null) return { kind: "unavailable" };
  const tables = state(sessionId);
  const requestedAt = now();
  const refuse = (code: VerifyRefusal): VerifyResult => {
    tables.audit.push({ code, organisation: enquirer.organisation, at: requestedAt });
    return { kind: "refused", code, requestedAt };
  };
  if (!enquirer.registered) return refuse("NOT_A_REGISTERED_COLLECTING_ORGANISATION");
  const at = Date.parse(input.at);
  if (at > Date.parse(requestedAt)) return refuse("INSTANT_IN_FUTURE");
  // A reference read aloud or copied is the same reference in either case.
  const premises = registerPremises(sessionId, input.premises.trim().toUpperCase());
  if (premises === null) return refuse("PREMISES_NOT_FOUND");

  // DR-201 rows 7 and 8: a premises nobody operated at the instant - closed, ceased, never begun - grants nobody.
  const relationship = premisesRelationshipAt(sessionId, premises.reference, { at: input.at });
  const operated = relationship.kind === "EFFECTIVE";
  const held = operated ? tables.authorities.filter((authority) => authority.premises === premises.reference) : [];
  const own = held.filter((authority) => authority.holder === enquirer.organisation);
  const ownInEffect = own.find((authority) => against(authority, at) === "inside") ?? null;
  const othersInEffect = held.some((authority) => authority.holder !== enquirer.organisation && against(authority, at) === "inside");
  const answer: VerificationAnswer = ownInEffect !== null ? "EFFECTIVE" : othersInEffect ? "ANOTHER_AUTHORITY_EXISTS" : "NOT_EFFECTIVE";
  // DR-201's evaluation order for the enquirer's own authority: exists, then not started, then expired.
  const reasonCode: ReasonCode = !operated
    ? relationship.kind === "ENDED"
      ? "RELATIONSHIP_ENDED"
      : "NO_RELATIONSHIP"
    : ownInEffect !== null
      ? "AUTHORITY_EFFECTIVE"
      : own.length === 0
        ? "NO_AUTHORITY"
        : own.some((authority) => against(authority, at) === "before")
          ? "AUTHORITY_NOT_STARTED"
          : "AUTHORITY_EXPIRED";

  tables.reads.push({
    id: randomUUID(),
    enquiringOrganisation: enquirer.organisation,
    premises: premises.reference,
    askedAtInstant: input.at,
    answer,
    reasonCode,
    readAt: requestedAt,
  });
  // The answer carries the enquirer's own period and nothing of anybody else's authority (SEC-206).
  const period = ownInEffect !== null && ownInEffect.from !== null && ownInEffect.to !== null ? { from: ownInEffect.from, to: ownInEffect.to } : null;
  return { kind: "answered", verification: { premises: { ...premises }, at: input.at, answer, period, readAt: requestedAt } };
}

/**
 * GET /premises/{id}/verification-reads for a collecting organisation: reserved to the data owner and
 * assurance, so refused with OVERLAP_REPORT_RESERVED, no enquiry of any organisation returned, and the refusal
 * recorded with its code (@AC-FR-PTY-047-05). Every reader the organisation portal signs in is one.
 */
export function readVerificationReads(sessionId: string, reader: { organisation: string }): LoadOutcome<never> {
  state(sessionId).audit.push({ code: "OVERLAP_REPORT_RESERVED", organisation: reader.organisation, at: now() });
  return { data: null, failure: { code: "OVERLAP_REPORT_RESERVED", traceId: null, retryable: false } };
}

const VN_START = (day: string) => Date.parse(`${day}T00:00:00${VN_OFFSET}`);

/**
 * GET /premises/{id}/verification-reads for the data owner and assurance (SCR-PTY-18 on the register data console):
 * every verification read of the premises, optionally from and to a day - which organisation asked, the instant it
 * asked about and the answer it was given - the overlap report DA-66 commissions the route for (@AC-FR-PTY-047-05).
 * The reads are read, never changed; a premises the register does not hold is PREMISES_NOT_FOUND. With no premises
 * named yet, the register to choose one from and no reads.
 */
export function overlapReport(staff: Staff, record: string, asked: { from: string | null; to: string | null }): LoadOutcome<OverlapReport> {
  if (!staff.roles.includes("ACT-DAT") && !staff.roles.includes("ACT-AUD")) return { data: null, failure: { code: "FORBIDDEN", traceId: null, retryable: false } };
  const named = record.trim().toUpperCase();
  const premises = named === "" ? null : registerPremises(staff.sessionId, named);
  if (named !== "" && premises === null) return { data: null, failure: { code: "PREMISES_NOT_FOUND", traceId: null, retryable: false } };
  const from = asked.from !== null ? VN_START(asked.from) : null;
  const until = asked.to !== null ? VN_START(asked.to) + 24 * 60 * 60 * 1000 : null;
  const rows = state(staff.sessionId)
    .reads.filter((read) => premises !== null && read.premises === premises.reference)
    .filter((read) => (from === null || Date.parse(read.readAt) >= from) && (until === null || Date.parse(read.readAt) < until))
    .sort((a, b) => Date.parse(b.readAt) - Date.parse(a.readAt))
    .map((read) => ({ id: read.id, organisation: { id: read.enquiringOrganisation, name: organisationName(read.enquiringOrganisation) }, askedAt: read.askedAtInstant, answer: read.answer, readAt: read.readAt }));
  return {
    data: {
      asOf: now(),
      premises,
      filter: { from: asked.from, to: asked.to },
      rows,
      organisations: new Set(rows.map((row) => row.organisation.id)).size,
      toldAnother: new Set(rows.filter((row) => row.answer === "ANOTHER_AUTHORITY_EXISTS").map((row) => row.organisation.id)).size,
      register: premisesRegister(staff.sessionId),
    },
    failure: null,
  };
}

