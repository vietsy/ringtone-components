#!/usr/bin/env node
/**
 * Writes the design system gallery from the design system R1's own specimens (components/r1/source/previews).
 *
 * Each specimen is a page that renders the component in its states with window.R1. This keeps the
 * expression it renders and its stylesheet, unchanged, and wraps each in a function the portal's gallery
 * calls with the generated R1 module, so `/design-system` shows every component exactly as the design
 * system presents it, rendered by the portal's own copy.
 *
 *   node scripts/generate-r1-gallery.mjs          write components/r1/generated/gallery.js and gallery.css
 *   node scripts/generate-r1-gallery.mjs --check  fail when either differs from what it would write
 */
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const previews = resolve(here, "../components/r1/source/previews");
const generated = (name) => resolve(here, "../components/r1/generated", name);

function fail(message) {
  process.stderr.write(`generate-r1-gallery: ${message}\n`);
  process.exit(1);
}

const OPEN = "  var R = window.R1, h = React.createElement;\n";
const RENDER = "ReactDOM.createRoot(document.getElementById('root')).render(";

function parse(name, html) {
  const card = /<!-- @dsCard group="([^"]+)" height=(\d+) -->/.exec(html);
  if (card === null) fail(`${name}: no @dsCard line.`);
  const script = /<script>\n([\s\S]*?)<\/script>/.exec(html);
  if (script === null) fail(`${name}: no script.`);
  let body = script[1];
  if (!body.startsWith(OPEN)) fail(`${name}: the script does not open with the R1 and createElement line.`);
  body = body.slice(OPEN.length);
  const at = body.indexOf(RENDER);
  if (at === -1) fail(`${name}: the script does not render into #root.`);
  const setup = body.slice(0, at);
  const expression = body.slice(at + RENDER.length).replace(/\);\s*$/, "");
  const style = /<style>([\s\S]*?)<\/style>/.exec(html);
  return { name, group: card[1], height: Number(card[2]), setup, expression, css: style === null ? "" : style[1].trim() };
}

/** Scopes a specimen's rules to its card, so `.pv` in one specimen does not style another. */
function scope(name, css) {
  return css.replace(/(^|\})\s*([^{}@]+)\{/g, (whole, close, selector) => {
    const scoped = selector
      .split(",")
      .map((part) => `[data-r1-preview="${name}"] ${part.trim()}`)
      .join(", ");
    return `${close}\n${scoped} {`;
  });
}

const files = readdirSync(previews).filter((file) => file.endsWith(".html")).sort();
const specimens = files.map((file) => parse(file.replace(/\.html$/, ""), readFileSync(resolve(previews, file), "utf8")));
const sha = createHash("sha256");
for (const file of files) sha.update(readFileSync(resolve(previews, file)));
const digest = sha.digest("hex");

const js = [
  '"use client";',
  `// Generated by scripts/generate-r1-gallery.mjs from components/r1/source/previews (${files.length} specimens, sha256 ${digest}).`,
  "// Do not edit: refresh the specimens from the design system and run the script.",
  'import * as React from "react";',
  'import * as R from "./r1.js";',
  "",
  "var h = React.createElement;",
  "",
  "export var SPECIMENS = [",
  ...specimens.map(
    (s) =>
      `  { name: ${JSON.stringify(s.name)}, group: ${JSON.stringify(s.group)}, height: ${s.height}, render: function () {\n${s.setup}  return (\n${s.expression}\n  );\n  } },`,
  ),
  "];",
  "",
].join("\n");

const css = `/* Generated by scripts/generate-r1-gallery.mjs from the design system's specimens. Do not edit. */\n${specimens
  .filter((s) => s.css !== "")
  .map((s) => scope(s.name, s.css).trim())
  .join("\n")}\n`;

const types = `// Generated by scripts/generate-r1-gallery.mjs. Do not edit.\nimport type * as React from "react";\nexport declare const SPECIMENS: { name: string; group: string; height: number; render: () => React.ReactElement }[];\n`;

const outputs = { "gallery.js": js, "gallery.css": css, "gallery.d.ts": types };

if (process.argv.includes("--check")) {
  const stale = Object.entries(outputs).filter(([name, text]) => {
    try {
      return readFileSync(generated(name), "utf8") !== text;
    } catch {
      return true;
    }
  });
  if (stale.length > 0) fail(`out of date: ${stale.map(([name]) => name).join(", ")}. Run pnpm --filter @rightone/portal generate:r1.`);
  process.stdout.write("generate-r1-gallery: up to date\n");
} else {
  for (const [name, text] of Object.entries(outputs)) writeFileSync(generated(name), text);
  process.stdout.write(`generate-r1-gallery: wrote ${Object.keys(outputs).join(", ")} from ${files.length} specimens\n`);
}
