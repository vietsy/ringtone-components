#!/usr/bin/env node
/**
 * Regenerates src/primitive.ts, src/semantic.ts and src/scale.ts from the RightOne Design System R1.
 *
 * R1 (https://claude.ai/artifact/7UFbwnuFWCvgVs6JXM8FaD, `project/tokens.json`) is the one source of
 * tokens (Design Brief 02-Design-Tokens.md 1.1). This package keeps a copy in r1/tokens.json so a build
 * never reaches the network, and this script is the only thing that turns that copy into code: a value
 * edited by hand in src/ would be overwritten by the next run, which is the point.
 *
 *   node scripts/generate-from-r1.mjs            # rewrite the three files
 *   node scripts/generate-from-r1.mjs --check    # exit 1 if any of them is stale
 *
 * No dependencies, so it runs on a machine where the workspace has not been installed. Every section
 * of the copy is either generated or refused: a section or a value shape this script does not know
 * stops it, because a token silently left out is a token nobody notices is missing.
 */
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const raw = readFileSync(join(root, "r1", "tokens.json"), "utf8");
const source = JSON.parse(raw);
const check = process.argv.includes("--check");

/** Every top-level key R1 writes, and where it goes. A new key in R1 must be added here on purpose. */
const SECTIONS = {
  name: "identity",
  version: "identity",
  meta: "identity",
  color: "PRIMITIVE, THEMES, STATUS_BY_THEME",
  type: "FONT_FAMILY, TYPE_STYLES",
  spacing: "SPACE",
  radius: "RADIUS",
  shadow: "SHADOW",
  fontSize: "FONT_SIZE",
  size: "SIZE",
  duration: "DURATION",
  breakpoint: "BREAKPOINT",
  zIndex: "Z_INDEX",
  lineHeight: "LINE_HEIGHT",
  fontWeight: "FONT_WEIGHT",
  letterSpacing: "LETTER_SPACING",
  easing: "EASING",
  opacity: "OPACITY",
  scale: "SCALE",
  backdrop: "BACKDROP",
};
const unknown = Object.keys(source).filter((k) => !(k in SECTIONS));
if (unknown.length > 0) throw new Error(`r1/tokens.json has sections this script does not generate: ${unknown.join(", ")}`);
// Below the top level each section has the shape this script reads: a token list of named values.
for (const [section, target] of Object.entries(SECTIONS)) {
  if (target === "identity" || section === "type") continue;
  const tokens = section === "color" ? source.color.tokens : source[section]?.tokens;
  if (!Array.isArray(tokens)) throw new Error(`${section} has no token list`);
  const odd = tokens.filter((t) => typeof t.name !== "string" || t.value === undefined);
  if (odd.length > 0) throw new Error(`${section} has a token with no name or no value`);
}
for (const key of ["fonts", "families", "groups"]) {
  if (!(key in source.type)) throw new Error(`type has no ${key}`);
}

const THEMES = source.color.themes.map((theme) => theme.id);
// Letters after a hyphen fold into camelCase; a hyphen before a digit stays (`chart-1`), so the portal's
// kebab() turns every key back into the R1 variable name.
const camel = (name) => name.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const quote = (value) => JSON.stringify(value);
const key = (name) => (/^[A-Za-z_$][\w$]*$/.test(camel(name)) ? camel(name) : quote(camel(name)));
const sha = createHash("sha256").update(raw).digest("hex").slice(0, 16);
const header = (what) =>
  `// Generated by scripts/generate-from-r1.mjs from r1/tokens.json (R1 ${source.name}, format v${source.version}, ` +
  `synced ${source.meta.synced}, sha256 ${sha}).\n` +
  `// Do not edit: change the design system, refresh r1/tokens.json, and run the script.\n` +
  `${what}\n`;

for (const t of source.color.tokens) {
  if (typeof t.value === "string") continue;
  if (t.value === null || typeof t.value !== "object") throw new Error(`Colour ${t.name} has a value of an unknown shape`);
  const missing = THEMES.filter((id) => typeof t.value[id] !== "string");
  if (missing.length > 0) throw new Error(`Colour ${t.name} has no value for ${missing.join(", ")}`);
}
const primitives = source.color.tokens.filter((t) => typeof t.value === "string");
const themed = source.color.tokens.filter((t) => typeof t.value === "object");
const primitiveValue = Object.fromEntries(primitives.map((t) => [t.name, t.value]));

function resolve(value) {
  const reference = /^\{(.+)\}$/.exec(value);
  if (reference === null) return value;
  const target = primitiveValue[reference[1]];
  if (target === undefined) throw new Error(`Unknown primitive ${reference[1]}`);
  return target;
}

function primitiveTs() {
  const lines = primitives.map((t) => `  ${quote(t.name)}: ${quote(t.value)},`);
  return (
    header(
      "/**\n * Tier 1, the raw ramps. No component references a primitive: it references a semantic token, which is\n" +
        " * what lets a ramp be retuned without hunting through components.\n */",
    ) +
    `export const PRIMITIVE = {\n${lines.join("\n")}\n} as const;\n\nexport type PrimitiveName = keyof typeof PRIMITIVE;\n`
  );
}

function semanticTs() {
  const theme = (id) =>
    `  ${id}: {\n` + themed.map((t) => `    ${key(t.name)}: ${quote(resolve(t.value[id]))},`).join("\n") + `\n  },`;
  const families = ["positive", "attention", "danger", "neutral", "info"];
  const status = (id) =>
    `  ${id}: {\n` +
    families
      .map((f) => {
        const pick = (role) => {
          const token = themed.find((t) => t.name === `${f}-${role}`);
          if (token === undefined) throw new Error(`Missing ${f}-${role}`);
          return resolve(token.value[id]);
        };
        return `    ${f}: { fill: ${quote(pick("fill"))}, tint: ${quote(pick("tint"))}, text: ${quote(pick("text"))} },`;
      })
      .join("\n") +
    `\n  },`;
  return (
    header(
      "/**\n * The only layer a component may use. One value per theme for every semantic and component colour:\n" +
        " * dark is the default for consoles, portals and public pages (there is no theme switch, R1 decision of\n" +
        " * 1 October 2026), light is paper (the printed record, a document sheet), player is the device and the\n" +
        " * guest display. A value is a six-digit hex, or rgba() for a see-through layer laid over its ground.\n */",
    ) +
    `export const THEMES = {\n${THEMES.map(theme).join("\n")}\n} as const;\n\n` +
    `export type ThemeName = keyof typeof THEMES;\nexport type SemanticName = keyof (typeof THEMES)["dark"];\n\n` +
    `/** The default theme, dark. Kept under this name because the portal emits it as its root variables. */\n` +
    `export const SEMANTIC = THEMES.dark;\n\n` +
    "/**\n * Five status families, each a fill, a tint and a separate text colour, because a fill is never legible\n" +
    " * as text. On the dark theme a tint is see-through and is measured over the card it sits on.\n */\n" +
    `export const STATUS_BY_THEME = {\n${THEMES.map(status).join("\n")}\n} as const;\n\n` +
    `export const STATUS = STATUS_BY_THEME.dark;\n\nexport type StatusFamily = keyof typeof STATUS;\n`
  );
}

function scaleTs() {
  const plain = (section, exportName, doc) => {
    const odd = source[section].tokens.filter((t) => typeof t.value !== "string");
    if (odd.length > 0) throw new Error(`${section}: ${odd.map((t) => t.name).join(", ")} is not a plain value`);
    const body = source[section].tokens.map((t) => `  ${quote(t.name)}: ${quote(t.value)},`).join("\n");
    return `/** ${doc} */\nexport const ${exportName} = {\n${body}\n} as const;\n`;
  };
  const shadow =
    "/** Elevation, one value per theme. */\nexport const SHADOW = {\n" +
    THEMES.map(
      (id) =>
        `  ${id}: {\n` +
        source.shadow.tokens
          .map((t) => {
            const value = typeof t.value === "string" ? t.value : t.value[id];
            if (typeof value !== "string") throw new Error(`shadow ${t.name} has no value for ${id}`);
            return `    ${quote(t.name)}: ${quote(value)},`;
          })
          .join("\n") +
        "\n  },",
    ).join("\n") +
    "\n} as const;\n";
  if (source.type.fonts.length > 0) throw new Error("type.fonts is no longer empty: decide where web fonts go before generating");
  const families = `/** Type families. System stacks: R1 loads no web font. */\nexport const FONT_FAMILY = ${JSON.stringify(source.type.families, null, 2)} as const;\n`;
  const style = (g, s) => {
    for (const field of ["name", "fontSize", "lineHeight", "fontWeight"]) {
      if (s[field] === undefined) throw new Error(`type style ${s.name ?? "?"} in ${g.name} has no ${field}`);
    }
    const weight = Number(s.fontWeight);
    if (!Number.isFinite(weight)) throw new Error(`type style ${s.name} in ${g.name} has a weight that is not a number`);
    return `      ${quote(s.name)}: { fontSize: ${quote(s.fontSize)}, lineHeight: ${quote(s.lineHeight)}, fontWeight: ${weight} },`;
  };
  const styles =
    "/** Type styles by group, as R1 names them, each group with its family and each style a size, a line height and a weight. */\n" +
    "export const TYPE_STYLES = {\n" +
    source.type.groups
      .map((g) => {
        if (!(g.family in source.type.families)) throw new Error(`type group ${g.name} names an unknown family ${g.family}`);
        return `  ${quote(g.name)}: {\n    family: ${quote(g.family)},\n    styles: {\n` + g.styles.map((s) => style(g, s)).join("\n") + "\n    },\n  },";
      })
      .join("\n") +
    "\n} as const;\n";
  return (
    header("/** Every token that is not a colour: the scales R1 shares with the Tailwind CSS v4 default theme, and its own. */") +
    [
      plain("spacing", "SPACE", "Spacing: one 4 px unit; space-N is N x 4 px."),
      plain("radius", "RADIUS", "Corner radius."),
      plain("fontSize", "FONT_SIZE", "Type sizes, product and appliance scales."),
      plain("lineHeight", "LINE_HEIGHT", "Line heights paired with the type sizes."),
      plain("fontWeight", "FONT_WEIGHT", "Weights: 400, 500 and 600 only."),
      plain("letterSpacing", "LETTER_SPACING", "Tracking."),
      plain("size", "SIZE", "Fixed sizes: rows, fields, targets, shells, the rail, content and container widths."),
      plain("duration", "DURATION", "Motion durations."),
      plain("easing", "EASING", "Motion curves."),
      plain("scale", "SCALE", "Scale factors for motion: where a dialog starts as it opens."),
      plain("breakpoint", "BREAKPOINT", "Breakpoints. The console is designed from bp-lg (1,024 px) and still reflows below it."),
      plain("zIndex", "Z_INDEX", "Layers."),
      plain("opacity", "OPACITY", "Opacities with a role."),
      plain("backdrop", "BACKDROP", "Backdrop filters for the glass materials; the light theme's glass is its own token."),
      shadow,
      families,
      styles,
    ].join("\n")
  );
}

const outputs = {
  "src/primitive.ts": primitiveTs(),
  "src/semantic.ts": semanticTs(),
  "src/scale.ts": scaleTs(),
};
const stale = [];
for (const [path, body] of Object.entries(outputs)) {
  const file = join(root, path);
  const current = existsSync(file) ? readFileSync(file, "utf8") : "";
  if (current === body) continue;
  if (check) stale.push(path);
  else writeFileSync(file, body);
}
if (check && stale.length > 0) {
  process.stderr.write(`stale: ${stale.join(", ")} - run pnpm --filter @rightone/tokens generate\n`);
  process.exit(1);
}
process.stdout.write(check ? "up to date\n" : `wrote ${Object.keys(outputs).join(", ")} from r1/tokens.json (sha256 ${sha})\n`);
